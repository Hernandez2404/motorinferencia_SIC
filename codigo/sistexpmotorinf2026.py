def motor_inferencia_avanzado(datos_iniciales, reglas):
    hechos = set(datos_iniciales.keys()) # Convertir datos iniciales a hechos
    hechos_nuevos = set() # Para llevar un registro de hechos recién agregados
    reglas_disparadas = set()

    while True:
        reglas_aplicables = []
        for i, regla in enumerate(reglas):
            # a) No repetir reglas ya disparadas
            if i not in reglas_disparadas:
                # Verificar si la regla se aplica (todos los antecedentes son hechos)
                antecedentes = set(regla["antecedentes"])

                # Verificar si todos los antecedentes están presentes en los hechos actuales
                if antecedentes.issubset(hechos):
                    reglas_aplicables.append((i, regla))

        # Mostrar el conjunto de conflictos (reglas aplicables)
        print("\nConjunto de conflictos (Reglas aplicables):")
        if reglas_aplicables:
            for _, regla in reglas_aplicables:
                print(f"- {regla['nombre']}")
        else:
            print("- Ninguna")


        if not reglas_aplicables:
            break # No hay reglas aplicables, detener la inferencia

        # *****  Resolver conflicto  *****
        # b) Seleccionar aquellas con mayor número de antecedentes
        reglas_aplicables.sort(key=lambda item: len(item[1]["antecedentes"]), reverse=True)

        # c) Seleccionar aquellas que tengan antecedentes recién agregados
        # (Esta parte requiere un seguimiento de qué hechos son nuevos, se puede implementar si es necesario)

        # d) Al azar (si hay empate después de las reglas anteriores)
        # En este ejemplo, si hay reglas con el mismo número de antecedentes,
        # se seleccionará la primera en el orden después de la clasificación.

        # Seleccionar la primera regla aplicable después de la resolución de conflictos
        indice_regla_seleccionada, regla_seleccionada = reglas_aplicables[0]

        # Mostrar la regla seleccionada
        print(f"\nRegla seleccionada: {regla_seleccionada['nombre']}")

        # Disparar la regla y agregar nuevos hechos (consecuentes)
        reglas_disparadas.add(indice_regla_seleccionada)

        nuevos_hechos_inferidos_por_regla = []
        for consecuente in regla_seleccionada["consecuentes"]:
            if consecuente not in hechos:
                hechos_nuevos.add(consecuente)
                hechos.add(consecuente)
                nuevos_hechos_inferidos_por_regla.append(consecuente)

        if nuevos_hechos_inferidos_por_regla:
            print(f"Regla disparada: {regla_seleccionada['nombre']}. Nuevos hechos agregados: {', '.join(nuevos_hechos_inferidos_por_regla)}")
        else:
            print(f"Regla disparada: {regla_seleccionada['nombre']}. No se agregaron nuevos hechos (ya existían o la regla no infiere nuevos).")

        # Ejecutar acción si existe (opcional)
        if "accion" in regla_seleccionada and callable(regla_seleccionada["accion"]):
            regla_seleccionada["accion"](hechos)

    return list(hechos)

